// 표 설계 → SQL. 새 표는 CREATE TABLE, 고친 표는 원래 설계(before)와 비교해 ALTER 문.
// SQLite는 ALTER로 못 하는 바뀜(타입·NULL·기본값·기본 키·외래 키)이면 표를 새로 만들어 데이터를 옮긴다.
// 돌려주는 문장에는 트랜잭션 줄까지 들어 있다 (미리 보기 = 실제 실행).
import { t } from './i18n'
import { quoteIdent } from './dialect'
import type { DesignColumn, DesignForeignKey, DesignIndex, Dialect, ExtraObject, FkAction, ObjectKind, TableDesign, TableRef } from './types'

export interface DesignSql {
  statements: string[]
  /** 미리 보기에 같이 보여 줄 주의 */
  warnings: string[]
}

type Where = { db: string; schema: string }

const same = (a: string[], b: string[]) => a.length === b.length && a.every((x, i) => x === b[i])
const low = (s: string) => s.toLowerCase()

function strLit(d: Dialect, s: string): string {
  let v = s.replace(/'/g, "''")
  if (d === 'mysql' || d === 'clickhouse') v = v.replace(/\\/g, '\\\\')
  return d === 'mssql' ? `N'${v}'` : `'${v}'`
}

/** ClickHouse: Nullable(T) ↔ T + NULL 허용 */
export function chUnwrap(type: string): { type: string; nullable: boolean } {
  const m = /^\s*Nullable\((.*)\)\s*$/s.exec(type)
  return m ? { type: m[1].trim(), nullable: true } : { type: type.trim(), nullable: false }
}
const chType = (c: DesignColumn) => {
  const inner = chUnwrap(c.type).type
  return c.nullable ? `Nullable(${inner})` : inner
}

/** 표 이름 (MySQL은 DB, PostgreSQL·SQL Server는 스키마까지. SQLite는 main이면 빼고) */
export function tableName(d: Dialect, w: Where, name: string): string {
  const q = (n: string) => quoteIdent(d, n)
  if (d === 'sqlite') return w.db && w.db !== 'main' ? `${q(w.db)}.${q(name)}` : q(name)
  if (d === 'mysql' || d === 'clickhouse') return w.db ? `${q(w.db)}.${q(name)}` : q(name)
  if (d === 'postgres' || d === 'oracle') return w.schema ? `${q(w.schema)}.${q(name)}` : q(name)
  if (d === 'duckdb') return [w.db, w.schema || 'main', name].filter(Boolean).map(q).join('.')
  return `${q(w.schema || 'dbo')}.${q(name)}`
}

function refName(d: Dialect, w: Where, fk: DesignForeignKey): string {
  const q = (n: string) => quoteIdent(d, n)
  // SQLite 외래 키는 같은 DB의 표만 (이름에 DB를 붙이면 문법 오류)
  if (d === 'sqlite') return q(fk.refTable)
  if (d === 'mysql') return `${q(fk.refSchema || w.db)}.${q(fk.refTable)}`
  const home = d === 'mssql' ? 'dbo' : d === 'duckdb' ? 'main' : d === 'oracle' ? '' : 'public'
  const schema = fk.refSchema || w.schema || home
  return schema ? `${q(schema)}.${q(fk.refTable)}` : q(fk.refTable)
}

const SQLITE_LITERAL = /^([+-]?\d+(\.\d+)?([eE][+-]?\d+)?|'([^']|'')*'|NULL|TRUE|FALSE|CURRENT_(TIME|DATE|TIMESTAMP)|[xX]'[0-9a-fA-F]*')$/i

/** SQLite 기본값: 글자·숫자가 아닌 식은 괄호로 감싸야 한다 */
function sqliteDefault(expr: string): string {
  const e = expr.trim()
  if (SQLITE_LITERAL.test(e) || /^\(.*\)$/s.test(e)) return e
  return `(${e})`
}

function colDef(d: Dialect, c: DesignColumn, inlinePk = false): string {
  const parts = [quoteIdent(d, c.name), c.type.trim()]
  if (d === 'mysql') {
    if (c.collation) parts.push('COLLATE ' + c.collation)
    parts.push(c.nullable ? 'NULL' : 'NOT NULL')
    if (c.default) parts.push('DEFAULT ' + c.default)
    if (c.onUpdate) parts.push('ON UPDATE ' + c.onUpdate)
    if (c.autoIncrement) parts.push('AUTO_INCREMENT')
    if (c.comment) parts.push('COMMENT ' + strLit(d, c.comment))
  } else if (d === 'postgres') {
    if (!c.nullable) parts.push('NOT NULL')
    if (c.autoIncrement) parts.push('GENERATED BY DEFAULT AS IDENTITY')
    else if (c.default) parts.push('DEFAULT ' + c.default)
  } else if (d === 'mssql') {
    if (c.autoIncrement) parts.push('IDENTITY(1,1)')
    parts.push(c.nullable ? 'NULL' : 'NOT NULL')
    if (c.default) parts.push('DEFAULT ' + c.default)
  } else if (d === 'oracle') {
    if (c.autoIncrement) parts.push('GENERATED BY DEFAULT ON NULL AS IDENTITY')
    else if (c.default) parts.push('DEFAULT ' + c.default)
    if (!c.nullable) parts.push('NOT NULL')
  } else if (d === 'duckdb') {
    if (!c.nullable) parts.push('NOT NULL')
    if (c.default) parts.push('DEFAULT ' + c.default)
  } else if (d === 'clickhouse') {
    parts[1] = chType(c)
    if (c.default) parts.push('DEFAULT ' + c.default)
    if (c.comment) parts.push('COMMENT ' + strLit(d, c.comment))
  } else {
    if (inlinePk) parts.push('PRIMARY KEY' + (c.autoIncrement ? ' AUTOINCREMENT' : ''))
    else if (!c.nullable) parts.push('NOT NULL')
    if (c.default) parts.push('DEFAULT ' + sqliteDefault(c.default))
  }
  return parts.join(' ')
}

const act = (w: string, a: FkAction) => (a && a !== 'NO ACTION' ? ` ON ${w} ${a}` : '')

/** 이름 없는 새 외래 키: fk_표_열 */
const fkAutoName = (table: string, fk: DesignForeignKey) => `fk_${table}_${fk.columns.join('_')}`.slice(0, 60)

function fkDef(d: Dialect, w: Where, table: string, fk: DesignForeignKey): string {
  const q = (n: string) => quoteIdent(d, n)
  // SQLite 외래 키는 이름 없이 (설계 화면의 #1 같은 이름은 구별용)
  const name = d === 'sqlite' ? '' : fk.name || fkAutoName(table, fk)
  return `${name ? `CONSTRAINT ${q(name)} ` : ''}FOREIGN KEY (${fk.columns.map(q).join(', ')}) REFERENCES ${refName(d, w, fk)} (${fk.refColumns.map(q).join(', ')})${act('DELETE', fk.onDelete)}${act('UPDATE', fk.onUpdate)}`
}

function indexCols(d: Dialect, ix: DesignIndex) {
  return ix.columns.map((c) => quoteIdent(d, c)).join(', ')
}

function createIndex(d: Dialect, w: Where, table: string, ix: DesignIndex): string {
  const q = (n: string) => quoteIdent(d, n)
  const tn = tableName(d, w, table)
  if (d === 'sqlite') {
    const name = w.db && w.db !== 'main' ? `${q(w.db)}.${q(ix.name)}` : q(ix.name)
    return `CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${name} ON ${q(table)} (${indexCols(d, ix)})`
  }
  if (ix.constraint && (d === 'postgres' || d === 'mssql' || d === 'oracle')) return `ALTER TABLE ${tn} ADD CONSTRAINT ${q(ix.name)} UNIQUE (${indexCols(d, ix)})`
  if (d === 'clickhouse') throw new Error(t('ClickHouse의 인덱스(데이터 건너뛰기 인덱스)는 설계 화면에서 만들 수 없어요. SQL 편집기에서 ALTER TABLE … ADD INDEX로 만들어 주세요.'))
  // Oracle 인덱스 이름은 스키마 안에서 (스키마를 붙인다)
  const ixName = d === 'oracle' && w.schema ? `${q(w.schema)}.${q(ix.name)}` : q(ix.name)
  return `CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${ixName} ON ${tn} (${indexCols(d, ix)})`
}

function dropIndex(d: Dialect, w: Where, table: string, ix: DesignIndex): string {
  const q = (n: string) => quoteIdent(d, n)
  const tn = tableName(d, w, table)
  if (d === 'sqlite') return `DROP INDEX ${w.db && w.db !== 'main' ? q(w.db) + '.' : ''}${q(ix.name)}`
  if (ix.constraint && (d === 'postgres' || d === 'mssql' || d === 'oracle')) return `ALTER TABLE ${tn} DROP CONSTRAINT ${q(ix.name)}`
  if (ix.constraint && d === 'duckdb') throw new Error(t('DuckDB는 이미 있는 표의 UNIQUE 제약을 지울 수 없어요'))
  if (d === 'postgres' || d === 'oracle') return `DROP INDEX ${w.schema ? q(w.schema) + '.' : ''}${q(ix.name)}`
  if (d === 'duckdb') return `DROP INDEX ${[w.db, w.schema || 'main'].filter(Boolean).map(q).join('.')}.${q(ix.name)}`
  if (d === 'clickhouse') return `ALTER TABLE ${tn} DROP INDEX ${q(ix.name)}`
  return `DROP INDEX ${q(ix.name)} ON ${tn}`
}

/** 설명 (PostgreSQL COMMENT ON, SQL Server MS_Description 확장 속성). column이 null이면 표 설명 */
function commentSql(d: Dialect, w: Where, table: string, column: string | null, text: string, existed: boolean): string | null {
  if (d === 'postgres' || d === 'duckdb' || d === 'oracle') {
    const target = column === null ? `TABLE ${tableName(d, w, table)}` : `COLUMN ${tableName(d, w, table)}.${quoteIdent(d, column)}`
    // Oracle은 NULL을 못 받아서 빈 글자로 지운다
    return `COMMENT ON ${target} IS ${text ? strLit(d, text) : d === 'oracle' ? "''" : 'NULL'}`
  }
  if (d === 'clickhouse') {
    const tn = tableName(d, w, table)
    return column === null ? `ALTER TABLE ${tn} MODIFY COMMENT ${strLit(d, text)}` : `ALTER TABLE ${tn} COMMENT COLUMN ${quoteIdent(d, column)} ${strLit(d, text)}`
  }
  if (d !== 'mssql') return null
  const lv = `@level0type = N'SCHEMA', @level0name = ${strLit(d, w.schema || 'dbo')}, @level1type = N'TABLE', @level1name = ${strLit(d, table)}` +
    (column === null ? '' : `, @level2type = N'COLUMN', @level2name = ${strLit(d, column)}`)
  if (!text) return existed ? `EXEC sys.sp_dropextendedproperty @name = N'MS_Description', ${lv}` : null
  return `EXEC sys.${existed ? 'sp_updateextendedproperty' : 'sp_addextendedproperty'} @name = N'MS_Description', @value = ${strLit(d, text)}, ${lv}`
}

/** SQL Server: 열의 기본값 제약(이름을 모름)을 찾아 지우기 */
function mssqlDropDefault(w: Where, table: string, column: string): string {
  const tn = tableName('mssql', w, table)
  return `DECLARE @df sysname = (SELECT dc.name FROM sys.default_constraints dc JOIN sys.columns c ON c.object_id = dc.parent_object_id AND c.column_id = dc.parent_column_id` +
    ` WHERE dc.parent_object_id = OBJECT_ID(${strLit('mssql', tn)}) AND c.name = ${strLit('mssql', column)});\n` +
    // EXEC( ) 안에서는 함수를 못 불러서 변수에 담아 실행
    `IF @df IS NOT NULL BEGIN DECLARE @sql nvarchar(max) = N'ALTER TABLE ${tn.replace(/'/g, "''")} DROP CONSTRAINT ' + QUOTENAME(@df); EXEC(@sql) END`
}

const isIntegerPk = (x: TableDesign) => x.primaryKey.length === 1 && x.columns.some((c) => low(c.name) === low(x.primaryKey[0]) && /^integer$/i.test(c.type.trim()))

/** 설계가 말이 되는지 (이름·타입·열 겹침·없는 열을 가리키는 키). 문제가 있으면 오류 */
export function checkDesign(d: Dialect, x: TableDesign): void {
  if (!x.name.trim()) throw new Error(t('표 이름을 적어 주세요'))
  if (!x.columns.length) throw new Error(t('열이 하나는 있어야 해요'))
  const names = new Set<string>()
  for (const c of x.columns) {
    if (!c.name.trim()) throw new Error(t('이름이 빈 열이 있어요'))
    if (names.has(low(c.name))) throw new Error(t('열 이름이 겹쳐요: {name}', { name: c.name }))
    names.add(low(c.name))
    if (c.generated) continue
    if (!c.type.trim()) throw new Error(t('{name} 열의 타입을 적어 주세요', { name: c.name }))
    if (c.autoIncrement && c.default.trim() && d !== 'mysql') throw new Error(t('{name}: 자동 증가 열에는 기본값을 둘 수 없어요', { name: c.name }))
    if (c.autoIncrement && (d === 'duckdb' || d === 'clickhouse')) throw new Error(t('{db}에는 자동 증가 열이 없어요. 기본값에 식(예: nextval(\'시퀀스\'))을 넣어 주세요.', { db: d === 'duckdb' ? 'DuckDB' : 'ClickHouse' }))
    if (c.autoIncrement && d === 'sqlite' && !(isIntegerPk(x) && low(x.primaryKey[0]) === low(c.name))) {
      throw new Error(t('SQLite의 자동 증가는 INTEGER 타입 기본 키 열 하나에만 돼요'))
    }
  }
  const has = (n: string) => names.has(low(n))
  for (const n of x.primaryKey) if (!has(n)) throw new Error(t('기본 키에 없는 열이 있어요: {name}', { name: n }))
  const ixNames = new Set<string>()
  for (const ix of x.indexes) {
    if (!ix.name.trim()) throw new Error(t('이름이 빈 인덱스가 있어요'))
    if (ixNames.has(low(ix.name))) throw new Error(t('인덱스 이름이 겹쳐요: {name}', { name: ix.name }))
    ixNames.add(low(ix.name))
    if (!ix.columns.length) throw new Error(t('{name} 인덱스에 열을 골라 주세요', { name: ix.name }))
    // 원래 문장을 그대로 쓰는 식 인덱스는 열 이름 검사를 건너뛴다
    if (!ix.sql) for (const c of ix.columns) if (!has(c)) throw new Error(t('{name} 인덱스에 없는 열이 있어요: {col}', { name: ix.name, col: c }))
  }
  for (const fk of x.foreignKeys) {
    const label = fk.name || fk.columns.join(', ')
    if (!fk.columns.length) throw new Error(t('외래 키에 열을 골라 주세요'))
    for (const c of fk.columns) if (!has(c)) throw new Error(t('{name} 외래 키에 없는 열이 있어요: {col}', { name: label, col: c }))
    if (!fk.refTable.trim()) throw new Error(t('{name} 외래 키가 참조할 표를 적어 주세요', { name: label }))
    if (fk.refColumns.length !== fk.columns.length || fk.refColumns.some((c) => !c.trim())) throw new Error(t('{name} 외래 키: 참조할 열 수가 열 수와 같아야 해요', { name: label }))
    if (d === 'mssql' && (fk.onDelete === 'RESTRICT' || fk.onUpdate === 'RESTRICT')) throw new Error(t('SQL Server에는 RESTRICT가 없어요 (NO ACTION이 같은 뜻이에요)'))
    if (d === 'oracle' && (fk.onUpdate !== 'NO ACTION' || fk.onDelete === 'RESTRICT' || fk.onDelete === 'SET DEFAULT')) throw new Error(t('Oracle 외래 키는 ON DELETE CASCADE·SET NULL만 돼요 (ON UPDATE는 없어요)'))
  }
  if (d === 'clickhouse' && x.foreignKeys.length) throw new Error(t('ClickHouse에는 외래 키가 없어요'))
}

/** CREATE TABLE (+ 인덱스·설명). name을 주면 그 이름으로 (SQLite 표 다시 만들기의 임시 표) */
function createTable(d: Dialect, w: Where, x: TableDesign, name = x.name): string[] {
  const q = (n: string) => quoteIdent(d, n)
  const inlinePk = d === 'sqlite' && isIntegerPk(x)
  const lines = x.columns.map((c) => '  ' + colDef(d, c, inlinePk && low(c.name) === low(x.primaryKey[0])))
  if (x.primaryKey.length && !inlinePk && d !== 'clickhouse') lines.push(`  ${x.pkName && d !== 'mysql' ? `CONSTRAINT ${q(x.pkName)} ` : ''}PRIMARY KEY (${x.primaryKey.map(q).join(', ')})`)
  for (const fk of x.foreignKeys) lines.push('  ' + fkDef(d, w, x.name, fk))
  let s = `CREATE TABLE ${tableName(d, w, name)} (\n${lines.join(',\n')}\n)`
  if (d === 'mysql' && x.comment) s += ' COMMENT = ' + strLit(d, x.comment)
  // ClickHouse: 엔진이 있어야 하고, 기본 키 = 정렬 키 (없으면 tuple())
  if (d === 'clickhouse') {
    s += `\nENGINE = ${x.options?.trim() || 'MergeTree'}\nORDER BY ${x.primaryKey.length ? `(${x.primaryKey.map(q).join(', ')})` : 'tuple()'}`
    if (x.comment) s += '\nCOMMENT ' + strLit(d, x.comment)
  }
  if (d === 'sqlite' && x.options) s += x.options
  const out = [s]
  for (const ix of x.indexes) out.push(createIndex(d, w, name, ix))
  if (d === 'clickhouse') return out
  if (x.comment) {
    const c = commentSql(d, w, name, null, x.comment, false)
    if (c) out.push(c)
  }
  for (const col of x.columns) {
    if (!col.comment) continue
    const c = commentSql(d, w, name, col.name, col.comment, false)
    if (c) out.push(c)
  }
  return out
}

const colChanged = (a: DesignColumn, b: DesignColumn) =>
  a.type.trim() !== b.type.trim() || a.nullable !== b.nullable || a.default.trim() !== b.default.trim() || a.autoIncrement !== b.autoIncrement
const ixSame = (a: DesignIndex, b: DesignIndex) => a.name === b.name && a.unique === b.unique && same(a.columns, b.columns) && !!a.constraint === !!b.constraint
const fkSame = (a: DesignForeignKey, b: DesignForeignKey) =>
  a.name === b.name && same(a.columns, b.columns) && a.refSchema === b.refSchema && a.refTable === b.refTable && same(a.refColumns, b.refColumns) && a.onDelete === b.onDelete && a.onUpdate === b.onUpdate

function wrap(d: Dialect, list: string[]): string[] {
  if (!list.length) return []
  if (d === 'postgres' || d === 'sqlite' || d === 'duckdb') return ['BEGIN', ...list, 'COMMIT']
  if (d === 'mssql') return ['BEGIN TRANSACTION', ...list, 'COMMIT']
  return list
}

/** 표 설계 → 실행할 문장. before = null이면 새 표 */
export function designSql(d: Dialect, w: Where, before: TableDesign | null, after: TableDesign): DesignSql {
  checkDesign(d, after)
  const warnings: string[] = []
  if (d === 'mysql' || d === 'oracle' || d === 'clickhouse') warnings.push(t('{db}은(는) 구조를 바꾸는 문장을 되돌릴 수 없어요. 중간에 오류가 나면 그 앞까지는 바뀐 채로 남아요.', { db: { mysql: 'MySQL', oracle: 'Oracle', clickhouse: 'ClickHouse' }[d] }))
  if (!before) return { statements: wrap(d, createTable(d, w, after)), warnings }

  const q = (n: string) => quoteIdent(d, n)
  const table = before.name
  const tn = tableName(d, w, table)
  const beforeCol = new Map(before.columns.map((c) => [c.name, c]))
  const keptOrig = new Set(after.columns.filter((c) => c.orig !== null).map((c) => c.orig!))
  const dropped = before.columns.filter((c) => !keptOrig.has(c.name))
  const added = after.columns.filter((c) => c.orig === null || !beforeCol.has(c.orig))
  const kept = after.columns.filter((c) => c.orig !== null && beforeCol.has(c.orig))
  const pkChanged = !same(before.primaryKey, after.primaryKey)

  const beforeIx = new Map(before.indexes.map((i) => [i.name, i]))
  const afterIxByOrig = new Map(after.indexes.filter((i) => i.orig !== null).map((i) => [i.orig!, i]))
  const ixDrop = before.indexes.filter((i) => { const a = afterIxByOrig.get(i.name); return !a || !ixSame(i, a) })
  const ixAdd = after.indexes.filter((i) => { const b = i.orig !== null ? beforeIx.get(i.orig) : undefined; return !b || !ixSame(b, i) })

  const beforeFk = new Map(before.foreignKeys.map((f) => [f.name, f]))
  const afterFkByOrig = new Map(after.foreignKeys.filter((f) => f.orig !== null).map((f) => [f.orig!, f]))
  const fkDrop = before.foreignKeys.filter((f) => { const a = afterFkByOrig.get(f.name); return !a || !fkSame(f, a) })
  const fkAdd = after.foreignKeys.filter((f) => { const b = f.orig !== null ? beforeFk.get(f.orig) : undefined; return !b || !fkSame(b, f) })
  const renamed = after.name !== before.name
  const commentChanged = after.comment !== before.comment

  for (const c of kept) {
    const b = beforeCol.get(c.orig!)!
    if (b.generated && colChanged(b, c)) throw new Error(t('{name}: 계산 열은 설계 화면에서 고칠 수 없어요', { name: c.name }))
  }

  if (d === 'sqlite') return sqliteAlter(w, before, after, { dropped, added, kept, pkChanged, ixDrop, ixAdd, fkDrop, fkAdd, renamed, beforeCol })
  const diff: Diff = { dropped, added, kept, pkChanged, ixDrop, ixAdd, fkDrop, fkAdd, renamed, beforeCol }
  if (d === 'oracle') return { statements: oracleAlter(w, before, after, diff), warnings }
  if (d === 'duckdb') return { statements: wrap(d, duckdbAlter(w, before, after, diff)), warnings }
  if (d === 'clickhouse') return { statements: clickhouseAlter(w, before, after, diff), warnings }

  if (d === 'mysql') {
    const out: string[] = []
    if (fkDrop.length) out.push(`ALTER TABLE ${tn} ${fkDrop.map((f) => `DROP FOREIGN KEY ${q(f.name)}`).join(', ')}`)
    const specs: string[] = []
    for (const i of ixDrop) specs.push(`DROP INDEX ${q(i.name)}`)
    if (pkChanged && before.primaryKey.length) specs.push('DROP PRIMARY KEY')
    for (const c of dropped) specs.push(`DROP COLUMN ${q(c.name)}`)
    for (const c of kept) {
      const b = beforeCol.get(c.orig!)!
      if (c.name === b.name && !colChanged(b, c) && c.comment === b.comment) continue
      // 타입을 바꾸면 원래 정렬 규칙은 빼고 (숫자 타입에 COLLATE를 붙이면 오류)
      const def = colDef(d, c.type.trim() === b.type.trim() ? c : { ...c, collation: undefined })
      specs.push(c.name === b.name ? `MODIFY COLUMN ${def}` : `CHANGE COLUMN ${q(b.name)} ${def}`)
    }
    for (const c of added) specs.push(`ADD COLUMN ${colDef(d, c)}`)
    if (pkChanged && after.primaryKey.length) specs.push(`ADD PRIMARY KEY (${after.primaryKey.map(q).join(', ')})`)
    for (const i of ixAdd) specs.push(`ADD ${i.unique ? 'UNIQUE ' : ''}INDEX ${q(i.name)} (${indexCols(d, i)})`)
    if (commentChanged) specs.push(`COMMENT = ${strLit(d, after.comment)}`)
    if (specs.length) out.push(`ALTER TABLE ${tn}\n  ${specs.join(',\n  ')}`)
    if (fkAdd.length) out.push(`ALTER TABLE ${tn}\n  ${fkAdd.map((f) => 'ADD ' + fkDef(d, w, after.name, f)).join(',\n  ')}`)
    if (renamed) out.push(`RENAME TABLE ${tn} TO ${tableName(d, w, after.name)}`)
    return { statements: out, warnings }
  }

  // PostgreSQL · SQL Server
  const out: string[] = []
  for (const f of fkDrop) out.push(`ALTER TABLE ${tn} DROP CONSTRAINT ${q(f.name)}`)
  for (const i of ixDrop) out.push(dropIndex(d, w, table, i))
  if (pkChanged && before.primaryKey.length) {
    if (!before.pkName) throw new Error(t('기본 키 제약 이름을 몰라서 지울 수 없어요'))
    out.push(`ALTER TABLE ${tn} DROP CONSTRAINT ${q(before.pkName)}`)
  }
  for (const c of dropped) {
    if (d === 'mssql' && c.default) out.push(mssqlDropDefault(w, table, c.name))
    out.push(`ALTER TABLE ${tn} DROP COLUMN ${q(c.name)}`)
  }
  for (const c of kept) {
    const b = beforeCol.get(c.orig!)!
    const col = q(c.name)
    if (c.name !== b.name) {
      out.push(d === 'postgres' ? `ALTER TABLE ${tn} RENAME COLUMN ${q(b.name)} TO ${col}` : `EXEC sp_rename ${strLit(d, `${tn}.${q(b.name)}`)}, ${strLit(d, c.name)}, N'COLUMN'`)
    }
    const typeChanged = c.type.trim() !== b.type.trim()
    const defChanged = c.default.trim() !== b.default.trim()
    if (d === 'postgres') {
      if (typeChanged) out.push(`ALTER TABLE ${tn} ALTER COLUMN ${col} TYPE ${c.type.trim()} USING ${col}::${c.type.trim()}`)
      if (c.nullable !== b.nullable) out.push(`ALTER TABLE ${tn} ALTER COLUMN ${col} ${c.nullable ? 'DROP' : 'SET'} NOT NULL`)
      if (b.autoIncrement && !c.autoIncrement) out.push(`ALTER TABLE ${tn} ALTER COLUMN ${col} DROP IDENTITY IF EXISTS`)
      if (defChanged && !c.autoIncrement) out.push(c.default.trim() ? `ALTER TABLE ${tn} ALTER COLUMN ${col} SET DEFAULT ${c.default.trim()}` : `ALTER TABLE ${tn} ALTER COLUMN ${col} DROP DEFAULT`)
      if (!b.autoIncrement && c.autoIncrement) out.push(`ALTER TABLE ${tn} ALTER COLUMN ${col} ADD GENERATED BY DEFAULT AS IDENTITY`)
    } else {
      if (b.autoIncrement !== c.autoIncrement) throw new Error(t('SQL Server는 이미 있는 열의 IDENTITY를 켜고 끌 수 없어요. 새 열을 만들어 옮겨 주세요.'))
      const alterCol = typeChanged || c.nullable !== b.nullable
      if ((alterCol || defChanged) && b.default) out.push(mssqlDropDefault(w, table, c.name))
      if (alterCol) out.push(`ALTER TABLE ${tn} ALTER COLUMN ${col} ${c.type.trim()} ${c.nullable ? 'NULL' : 'NOT NULL'}`)
      if ((alterCol || defChanged) && c.default.trim()) out.push(`ALTER TABLE ${tn} ADD DEFAULT ${c.default.trim()} FOR ${col}`)
    }
    if (c.comment !== b.comment) {
      const s = commentSql(d, w, table, c.name, c.comment, !!b.comment)
      if (s) out.push(s)
    }
  }
  for (const c of added) {
    // SQL Server는 NULL 허용 열을 추가할 때 WITH VALUES가 있어야 이미 있는 행에도 기본값을 넣는다 (다른 DB와 같게)
    out.push(`ALTER TABLE ${tn} ADD ${d === 'postgres' ? 'COLUMN ' : ''}${colDef(d, c)}${d === 'mssql' && c.default.trim() ? ' WITH VALUES' : ''}`)
    if (c.comment) {
      const s = commentSql(d, w, table, c.name, c.comment, false)
      if (s) out.push(s)
    }
  }
  if (pkChanged && after.primaryKey.length) {
    const name = after.pkName || before.pkName
    out.push(`ALTER TABLE ${tn} ADD ${name ? `CONSTRAINT ${q(name)} ` : ''}PRIMARY KEY (${after.primaryKey.map(q).join(', ')})`)
  }
  for (const i of ixAdd) out.push(createIndex(d, w, table, i))
  for (const f of fkAdd) out.push(`ALTER TABLE ${tn} ADD ${fkDef(d, w, after.name, f)}`)
  if (commentChanged) {
    const s = commentSql(d, w, table, null, after.comment, !!before.comment)
    if (s) out.push(s)
  }
  if (renamed) out.push(d === 'postgres' ? `ALTER TABLE ${tn} RENAME TO ${q(after.name)}` : `EXEC sp_rename ${strLit(d, tn)}, ${strLit(d, after.name)}`)
  return { statements: wrap(d, out), warnings }
}

interface Diff {
  dropped: DesignColumn[]
  added: DesignColumn[]
  kept: DesignColumn[]
  pkChanged: boolean
  ixDrop: DesignIndex[]
  ixAdd: DesignIndex[]
  fkDrop: DesignForeignKey[]
  fkAdd: DesignForeignKey[]
  renamed: boolean
  beforeCol: Map<string, DesignColumn>
}

/** SQLite: 표를 만들 때 생긴 UNIQUE 제약 인덱스(sqlite_autoindex_…) — DROP INDEX로 못 지운다 */
const autoIndex = (i: DesignIndex) => !!i.constraint

function sqliteAlter(w: Where, before: TableDesign, after: TableDesign, x: Diff): DesignSql {
  const d: Dialect = 'sqlite'
  const q = (n: string) => quoteIdent(d, n)
  const table = before.name
  const tn = tableName(d, w, table)
  const rebuild = x.pkChanged || x.fkDrop.length > 0 || x.fkAdd.length > 0 || x.ixDrop.some(autoIndex) ||
    x.kept.some((c) => colChanged(x.beforeCol.get(c.orig!)!, c)) || x.added.some((c) => c.generated)
  const warnings: string[] = []

  if (!rebuild) {
    const out: string[] = []
    for (const i of x.ixDrop) out.push(dropIndex(d, w, table, i))
    for (const c of x.kept) {
      const b = x.beforeCol.get(c.orig!)!
      if (c.name !== b.name) out.push(`ALTER TABLE ${tn} RENAME COLUMN ${q(b.name)} TO ${q(c.name)}`)
    }
    for (const c of x.dropped) out.push(`ALTER TABLE ${tn} DROP COLUMN ${q(c.name)}`)
    for (const c of x.added) out.push(`ALTER TABLE ${tn} ADD COLUMN ${colDef(d, c)}`)
    for (const i of x.ixAdd) out.push(createIndex(d, w, table, i))
    if (x.renamed) out.push(`ALTER TABLE ${tn} RENAME TO ${q(after.name)}`)
    return { statements: wrap(d, out), warnings }
  }

  if (before.unsupported.length) {
    throw new Error(t('이 표에는 설계 화면이 다루지 않는 설정({list})이 있어서, 표를 새로 만들어야 하는 바뀜(타입·NULL·기본값·기본 키·외래 키)은 할 수 없어요. SQL 편집기에서 직접 바꿔 주세요.', { list: before.unsupported.join(', ') }))
  }
  warnings.push(t('SQLite는 이 바뀜을 ALTER로 못 해서, 새 표를 만들어 데이터를 옮기고 원래 표를 지운 뒤 이름을 바꿔요. 인덱스·트리거는 다시 만들어요.'))
  const tmp = `_dboard_new_${table}`.slice(0, 120)
  const copy = x.kept.filter((c) => !c.generated)
  const out = [
    'PRAGMA foreign_keys = OFF',
    'PRAGMA legacy_alter_table = ON',
    'BEGIN',
    createTable(d, w, { ...after, name: table, indexes: [] }, tmp)[0],
    `INSERT INTO ${tableName(d, w, tmp)} (${copy.map((c) => q(c.name)).join(', ')}) SELECT ${copy.map((c) => q(c.orig!)).join(', ')} FROM ${tn}`,
    `DROP TABLE ${tn}`,
    `ALTER TABLE ${tableName(d, w, tmp)} RENAME TO ${q(table)}`,
  ]
  const beforeIx = new Map(before.indexes.map((i) => [i.name, i]))
  for (const i of after.indexes) {
    const b = i.orig !== null ? beforeIx.get(i.orig) : undefined
    // 바뀌지 않은 인덱스는 원래 문장 그대로 (식·조건 인덱스도 살린다). UNIQUE 제약 인덱스는 이름을 새로 붙여 인덱스로
    if (b && ixSame(b, i) && i.sql) out.push(i.sql)
    // sqlite_로 시작하는 이름은 쓸 수 없다
    else out.push(createIndex(d, w, table, i.name.startsWith('sqlite_') ? { ...i, name: `uq_${table}_${i.columns.join('_')}` } : i))
  }
  for (const tr of before.triggers ?? []) out.push(tr)
  out.push('PRAGMA legacy_alter_table = OFF')
  if (x.renamed) out.push(`ALTER TABLE ${tn} RENAME TO ${q(after.name)}`)
  out.push('COMMIT', 'PRAGMA foreign_keys = ON')
  return { statements: out, warnings }
}

/** Oracle: MODIFY는 바뀐 것만 (NOT NULL을 다시 걸면 ORA-01442). DDL은 문장마다 커밋돼서 트랜잭션 줄이 없다 */
function oracleAlter(w: Where, before: TableDesign, after: TableDesign, x: Diff): string[] {
  const d: Dialect = 'oracle'
  const q = (n: string) => quoteIdent(d, n)
  const tn = tableName(d, w, before.name)
  const out: string[] = []
  for (const f of x.fkDrop) out.push(`ALTER TABLE ${tn} DROP CONSTRAINT ${q(f.name)}`)
  for (const i of x.ixDrop) out.push(dropIndex(d, w, before.name, i))
  if (x.pkChanged && before.primaryKey.length) {
    if (!before.pkName) throw new Error(t('기본 키 제약 이름을 몰라서 지울 수 없어요'))
    out.push(`ALTER TABLE ${tn} DROP CONSTRAINT ${q(before.pkName)}`)
  }
  for (const c of x.dropped) out.push(`ALTER TABLE ${tn} DROP COLUMN ${q(c.name)}`)
  for (const c of x.kept) {
    const b = x.beforeCol.get(c.orig!)!
    const col = q(c.name)
    if (c.name !== b.name) out.push(`ALTER TABLE ${tn} RENAME COLUMN ${q(b.name)} TO ${col}`)
    if (!b.autoIncrement && c.autoIncrement) throw new Error(t('Oracle은 이미 있는 열을 자동 증가(IDENTITY)로 바꿀 수 없어요. 새 열을 만들어 옮겨 주세요.'))
    if (b.autoIncrement && !c.autoIncrement) out.push(`ALTER TABLE ${tn} MODIFY (${col} DROP IDENTITY)`)
    const parts: string[] = []
    if (c.type.trim() !== b.type.trim()) parts.push(c.type.trim())
    if (c.default.trim() !== b.default.trim() && !c.autoIncrement) parts.push('DEFAULT ' + (c.default.trim() || 'NULL'))
    if (c.nullable !== b.nullable) parts.push(c.nullable ? 'NULL' : 'NOT NULL')
    if (parts.length) out.push(`ALTER TABLE ${tn} MODIFY (${col} ${parts.join(' ')})`)
    if (c.comment !== b.comment) out.push(commentSql(d, w, before.name, c.name, c.comment, !!b.comment)!)
  }
  for (const c of x.added) {
    out.push(`ALTER TABLE ${tn} ADD (${colDef(d, c)})`)
    if (c.comment) out.push(commentSql(d, w, before.name, c.name, c.comment, false)!)
  }
  if (x.pkChanged && after.primaryKey.length) {
    const name = after.pkName || before.pkName
    out.push(`ALTER TABLE ${tn} ADD ${name ? `CONSTRAINT ${q(name)} ` : ''}PRIMARY KEY (${after.primaryKey.map(q).join(', ')})`)
  }
  for (const i of x.ixAdd) out.push(createIndex(d, w, before.name, i))
  for (const f of x.fkAdd) out.push(`ALTER TABLE ${tn} ADD ${fkDef(d, w, after.name, f)}`)
  if (after.comment !== before.comment) out.push(commentSql(d, w, before.name, null, after.comment, !!before.comment)!)
  if (x.renamed) out.push(`ALTER TABLE ${tn} RENAME TO ${q(after.name)}`)
  return out
}

/** DuckDB: 이미 있는 표에는 외래 키를 더하거나 뺄 수 없고, 기본 키는 없던 표에 더하기만 된다 */
function duckdbAlter(w: Where, before: TableDesign, after: TableDesign, x: Diff): string[] {
  const d: Dialect = 'duckdb'
  const q = (n: string) => quoteIdent(d, n)
  const tn = tableName(d, w, before.name)
  if (x.fkDrop.length || x.fkAdd.length) throw new Error(t('DuckDB는 이미 있는 표의 외래 키를 바꿀 수 없어요. 새 표를 만들어 데이터를 옮겨 주세요.'))
  if (x.pkChanged && before.primaryKey.length) throw new Error(t('DuckDB는 이미 있는 표의 기본 키를 바꾸거나 지울 수 없어요. 새 표를 만들어 데이터를 옮겨 주세요.'))
  const out: string[] = []
  for (const i of x.ixDrop) out.push(dropIndex(d, w, before.name, i))
  for (const c of x.dropped) out.push(`ALTER TABLE ${tn} DROP COLUMN ${q(c.name)}`)
  for (const c of x.kept) {
    const b = x.beforeCol.get(c.orig!)!
    const col = q(c.name)
    if (c.name !== b.name) out.push(`ALTER TABLE ${tn} RENAME COLUMN ${q(b.name)} TO ${col}`)
    if (c.type.trim() !== b.type.trim()) out.push(`ALTER TABLE ${tn} ALTER COLUMN ${col} TYPE ${c.type.trim()}`)
    if (c.nullable !== b.nullable) out.push(`ALTER TABLE ${tn} ALTER COLUMN ${col} ${c.nullable ? 'DROP' : 'SET'} NOT NULL`)
    if (c.default.trim() !== b.default.trim()) out.push(c.default.trim() ? `ALTER TABLE ${tn} ALTER COLUMN ${col} SET DEFAULT ${c.default.trim()}` : `ALTER TABLE ${tn} ALTER COLUMN ${col} DROP DEFAULT`)
    if (c.comment !== b.comment) out.push(commentSql(d, w, before.name, c.name, c.comment, !!b.comment)!)
  }
  for (const c of x.added) {
    out.push(`ALTER TABLE ${tn} ADD COLUMN ${colDef(d, c)}`)
    if (c.comment) out.push(commentSql(d, w, before.name, c.name, c.comment, false)!)
  }
  if (x.pkChanged && after.primaryKey.length) out.push(`ALTER TABLE ${tn} ADD PRIMARY KEY (${after.primaryKey.map(q).join(', ')})`)
  for (const i of x.ixAdd) {
    if (i.constraint) throw new Error(t('DuckDB는 이미 있는 표에 UNIQUE 제약을 더할 수 없어요. 고유 인덱스로 만들어 주세요.'))
    out.push(createIndex(d, w, before.name, i))
  }
  if (after.comment !== before.comment) out.push(commentSql(d, w, before.name, null, after.comment, !!before.comment)!)
  if (x.renamed) out.push(`ALTER TABLE ${tn} RENAME TO ${q(after.name)}`)
  return out
}

/** ClickHouse: 정렬 키(기본 키)는 바꿀 수 없다. NULL 허용은 타입 Nullable(…)로 */
function clickhouseAlter(w: Where, before: TableDesign, after: TableDesign, x: Diff): string[] {
  const d: Dialect = 'clickhouse'
  const q = (n: string) => quoteIdent(d, n)
  const tn = tableName(d, w, before.name)
  if (x.pkChanged) throw new Error(t('ClickHouse는 이미 있는 표의 기본 키(정렬 키)를 바꿀 수 없어요. 새 표를 만들어 데이터를 옮겨 주세요.'))
  const out: string[] = []
  for (const i of x.ixDrop) out.push(dropIndex(d, w, before.name, i))
  for (const c of x.dropped) out.push(`ALTER TABLE ${tn} DROP COLUMN ${q(c.name)}`)
  for (const c of x.kept) {
    const b = x.beforeCol.get(c.orig!)!
    const col = q(c.name)
    if (c.name !== b.name) out.push(`ALTER TABLE ${tn} RENAME COLUMN ${q(b.name)} TO ${col}`)
    const typeChanged = chType(c) !== chType(b)
    if (typeChanged || c.default.trim() !== b.default.trim()) {
      out.push(`ALTER TABLE ${tn} MODIFY COLUMN ${col} ${chType(c)}${c.default.trim() ? ' DEFAULT ' + c.default.trim() : ''}`)
      if (!c.default.trim() && b.default.trim()) out.push(`ALTER TABLE ${tn} MODIFY COLUMN ${col} REMOVE DEFAULT`)
    }
    if (c.comment !== b.comment) out.push(commentSql(d, w, before.name, c.name, c.comment, !!b.comment)!)
  }
  for (const c of x.added) out.push(`ALTER TABLE ${tn} ADD COLUMN ${colDef(d, c)}`)
  for (const i of x.ixAdd) out.push(createIndex(d, w, before.name, i))
  if (after.comment !== before.comment) out.push(commentSql(d, w, before.name, null, after.comment, !!before.comment)!)
  if (x.renamed) out.push(`RENAME TABLE ${tn} TO ${tableName(d, w, after.name)}`)
  return out
}

export type ObjectAction = 'rename' | 'truncate' | 'drop'

/** 탐색기 메뉴의 이름 바꾸기·비우기·지우기 */
export function objectSql(d: Dialect, ref: TableRef, kind: ObjectKind, action: ObjectAction, newName = ''): string[] {
  const q = (n: string) => quoteIdent(d, n)
  const tn = tableName(d, ref, ref.table)
  const word = kind === 'view' ? 'VIEW' : 'TABLE'
  if (action === 'drop') return [`DROP ${word} ${tn}`]
  if (action === 'truncate') {
    if (kind === 'view') throw new Error(t('뷰는 비울 수 없어요'))
    return [d === 'sqlite' || d === 'duckdb' ? `DELETE FROM ${tn}` : `TRUNCATE TABLE ${tn}`]
  }
  const name = newName.trim()
  if (!name) throw new Error(t('새 이름을 적어 주세요'))
  if (d === 'sqlite') {
    if (kind === 'view') throw new Error(t('SQLite는 뷰 이름을 바꿀 수 없어요 (지우고 새로 만들어 주세요)'))
    return [`ALTER TABLE ${tn} RENAME TO ${q(name)}`]
  }
  if (d === 'mysql' || d === 'clickhouse') return [`RENAME TABLE ${tn} TO ${tableName(d, ref, name)}`]
  if (d === 'postgres' || d === 'duckdb') return [`ALTER ${word} ${tn} RENAME TO ${q(name)}`]
  // Oracle 뷰는 RENAME (자기 스키마만)
  if (d === 'oracle') return [kind === 'view' ? `RENAME ${q(ref.table)} TO ${q(name)}` : `ALTER TABLE ${tn} RENAME TO ${q(name)}`]
  return [`EXEC sp_rename ${strLit(d, tn)}, ${strLit(d, name)}`]
}

/** 프로시저·함수·트리거·시퀀스·이벤트 지우기 */
export function dropExtraSql(d: Dialect, w: Where, x: ExtraObject): string {
  const q = (n: string) => quoteIdent(d, n)
  const word = { procedure: 'PROCEDURE', function: 'FUNCTION', package: 'PACKAGE', trigger: 'TRIGGER', sequence: 'SEQUENCE', event: 'EVENT' }[x.kind]
  if (d === 'sqlite') return `DROP TRIGGER ${tableName(d, w, x.name)}`
  // DuckDB 함수 = 매크로
  if (d === 'duckdb') return x.kind === 'function' ? `DROP MACRO ${tableName(d, w, x.name)}` : `DROP ${word} ${tableName(d, w, x.name)}`
  if (d === 'oracle') return `DROP ${word} ${tableName(d, w, x.name)}`
  if (d === 'mysql') return `DROP ${word} ${tableName(d, w, x.name)}`
  if (d === 'postgres') {
    // 같은 이름 함수가 여럿일 수 있어서 인자까지. 트리거는 표 이름과 함께
    if (x.kind === 'trigger') return `DROP TRIGGER ${q(x.name)} ON ${tableName(d, w, x.table)}`
    if (x.kind === 'procedure' || x.kind === 'function') return `DROP ${word} ${tableName(d, w, x.name)}(${x.args})`
    return `DROP ${word} ${tableName(d, w, x.name)}`
  }
  return `DROP ${word} ${tableName(d, w, x.name)}`
}
