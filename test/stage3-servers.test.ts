import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { Manager, type Live } from '../src/main/conn'
import { compareSchemas } from '../src/main/compare'
import { runStatements } from '../src/main/dump'
import { erModel } from '../src/main/er'
import { transferData } from '../src/main/transfer'
import { quoteIdent } from '../src/shared/dialect'
import type { Dialect, DriverKind } from '../src/shared/types'
import { config, memoryKeys, resolved } from './exercise'

const ON = process.env.DBOARD_TEST_DBS === '1'
const rand = () => Math.random().toString(36).slice(2, 8)
const O = { showSystem: false }

const SRC: Record<'mysql' | 'postgres' | 'mssql', string[]> = {
  mysql: [
    'CREATE TABLE parent (id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(50) NOT NULL, note TEXT)',
    'CREATE TABLE child (id INT PRIMARY KEY, parent_id INT, qty INT DEFAULT 1, CONSTRAINT fk_child_parent FOREIGN KEY (parent_id) REFERENCES parent (id))',
    'CREATE INDEX child_qty ON child (qty)',
  ],
  postgres: [
    'CREATE TABLE parent (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(50) NOT NULL, note text)',
    'CREATE TABLE child (id integer PRIMARY KEY, parent_id integer CONSTRAINT fk_child_parent REFERENCES parent (id), qty integer DEFAULT 1)',
    'CREATE INDEX child_qty ON child (qty)',
  ],
  mssql: [
    'CREATE TABLE parent (id INT IDENTITY(1,1) PRIMARY KEY, name NVARCHAR(50) NOT NULL, note NVARCHAR(MAX))',
    'CREATE TABLE child (id INT PRIMARY KEY, parent_id INT, qty INT DEFAULT 1, CONSTRAINT fk_child_parent FOREIGN KEY (parent_id) REFERENCES parent (id))',
    'CREATE INDEX child_qty ON child (qty)',
  ],
}
const DST: Record<'mysql' | 'postgres' | 'mssql', string[]> = {
  mysql: ['CREATE TABLE parent (id INT AUTO_INCREMENT PRIMARY KEY, name INT, extra INT)'],
  postgres: ['CREATE TABLE parent (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name integer, extra integer)'],
  mssql: ['CREATE TABLE parent (id INT IDENTITY(1,1) PRIMARY KEY, name INT, extra INT)'],
}

async function withDb<T>(m: Manager, kind: DriverKind, fn: (id: string, db: string, schema: string) => Promise<T>): Promise<T> {
  const d = kind === 'mariadb' ? 'mysql' : (kind as 'mysql' | 'postgres' | 'mssql')
  const db = 'dboard_s3_' + rand()
  const base = kind === 'postgres' ? config('postgres', { database: 'dboard_test' }) : config(kind)
  const adminId = 'admin-' + kind + rand()
  const admin = await m.connect(adminId, resolved(base))
  const adminExec = async (sql: string) => (await admin.metaSession(kind === 'postgres' ? 'dboard_test' : undefined)).exec(sql)
  await adminExec(`CREATE DATABASE ${quoteIdent(d, db)}`)
  const id = kind + '-' + rand()
  try {
    await m.connect(id, resolved(kind === 'postgres' ? config('postgres', { database: db }) : base))
    return await fn(id, db, kind === 'postgres' ? 'public' : kind === 'mssql' ? 'dbo' : '')
  } finally {
    await m.disconnect(id).catch(() => undefined)
    await adminExec(d === 'mssql' ? `ALTER DATABASE ${quoteIdent(d, db)} SET SINGLE_USER WITH ROLLBACK IMMEDIATE; DROP DATABASE ${quoteIdent(d, db)}` : `DROP DATABASE ${quoteIdent(d, db)}`).catch((e) => console.warn(String(e)))
    await m.disconnect(adminId).catch(() => undefined)
  }
}

const side = async (live: Live, db: string, schema: string) => ({ mod: live.mod, s: await live.metaSession(db), db, schema, o: O })

describe.skipIf(!ON)('stage 3-1 on real servers', () => {
  for (const kind of ['mysql', 'mariadb', 'postgres', 'mssql'] as DriverKind[]) {
    it(`${kind}: compare, transfer, ER`, async () => {
      const m = new Manager(memoryKeys())
      const d = kind === 'mariadb' ? 'mysql' : (kind as 'mysql' | 'postgres' | 'mssql')
      try {
        await withDb(m, kind, (a, adb, asch) => withDb(m, kind, async (b, bdb, bsch) => {
          const la = m.get(a)
          const lb = m.get(b)
          const run = async (id: string, db: string, schema: string, list: string[]) => {
            const s = await m.editorSession(id, 'ddl', db, schema)
            try {
              await runStatements(s, d, list)
            } finally {
              await m.closeEditor('ddl')
            }
          }
          await run(a, adb, asch, SRC[d])
          await run(b, bdb, bsch, DST[d])
          const sa = await m.editorSession(a, 'w', adb, asch)
          await sa.run(`INSERT INTO parent (name, note) VALUES (${d === 'mssql' ? "N'p1'" : "'p1'"}, NULL)`, 1)
          await sa.run(`INSERT INTO parent (name, note) VALUES (${d === 'mssql' ? "N'p2'" : "'p2'"}, ${d === 'mssql' ? "N'n'" : "'n'"})`, 1)
          await sa.run('INSERT INTO child (id, parent_id, qty) VALUES (1, 1, 3)', 1)

          const er = await erModel(la.mod, await la.metaSession(adb), adb, asch, O)
          expect(er.links.map((l) => `${l.from}>${l.to}`)).toEqual(['child>parent'])

          const r = await compareSchemas(await side(la, adb, asch), await side(lb, bdb, bsch))
          const by = Object.fromEntries(r.items.map((x) => [x.name, x]))
          expect(by.child.status).toBe('source')
          expect(by.parent.status).toBe('changed')
          expect(r.items.every((x) => x.error === null)).toBe(true)
          await run(b, bdb, bsch, r.items.filter((x) => x.status === 'source' || x.status === 'changed').flatMap((x) => x.statements))
          const again = await compareSchemas(await side(la, adb, asch), await side(lb, bdb, bsch))
          expect(again.items.filter((x) => x.kind === 'table' && x.status !== 'same').map((x) => `${x.name}: ${x.changes.join(', ')}`)).toEqual([])

          const tr = await m.editorSession(a, 'tr-src', adb, asch)
          const tw = await m.editorSession(b, 'tr', bdb, bsch)
          const res = await transferData({ mod: la.mod, s: tr, db: adb, schema: asch, o: O }, { mod: lb.mod, s: tw, db: bdb, schema: bsch, o: O }, ['child', 'parent'], { create: false, truncate: true, batch: 500, stopOnError: true }, () => false)
          expect(res.tables.map((x) => [x.name, x.rows, x.error])).toEqual([['parent', 2, null], ['child', 1, null]])
          // 자동 번호가 옮긴 값 다음부터 이어진다
          const sb = await m.editorSession(b, 'w2', bdb, bsch)
          await sb.run(`INSERT INTO parent (name) VALUES (${d === 'mssql' ? "N'p3'" : "'p3'"})`, 1)
          expect(Number((await sb.query('SELECT MAX(id) FROM parent')).rows[0][0])).toBe(3)
        }))
      } finally {
        await m.disconnectAll()
      }
    })
  }

  it('transfers between different databases (PostgreSQL → MySQL · MariaDB · SQL Server · SQLite)', async () => {
    const m = new Manager(memoryKeys())
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dboard-s3x-'))
    try {
      await withDb(m, 'postgres', async (pg, pdb, psch) => {
        const s = await m.editorSession(pg, 'w', pdb, psch)
        await s.run(`CREATE TABLE items (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name varchar(40) NOT NULL DEFAULT 'x', price numeric(10,2),
          active boolean, made timestamp, data bytea, meta jsonb, note text)`, 1)
        await s.run(`INSERT INTO items (name, price, active, made, data, meta, note) VALUES ('가나다', 12.50, true, '2024-03-01 10:20:30', '\\x00ff10', '{"a":1}', NULL), ('b', NULL, false, NULL, NULL, NULL, 'n')`, 1)
        const lp = m.get(pg)
        const targets: [DriverKind, Dialect][] = [['mysql', 'mysql'], ['mariadb', 'mysql'], ['mssql', 'mssql']]
        for (const [kind, d] of targets) {
          await withDb(m, kind, async (x, xdb, xsch) => {
            const lx = m.get(x)
            const res = await transferData({ mod: lp.mod, s: await m.editorSession(pg, 'src', pdb, psch), db: pdb, schema: psch, o: O },
              { mod: lx.mod, s: await m.editorSession(x, 'dst', xdb, xsch), db: xdb, schema: xsch, o: O }, ['items'], { create: true, truncate: false, batch: 100, stopOnError: true }, () => false)
            expect(res.tables[0]).toMatchObject({ name: 'items', rows: 2, created: true, error: null })
            const q = await (await m.editorSession(x, 'chk', xdb, xsch)).query(`SELECT ${['id', 'name', 'price', 'active'].map((c) => quoteIdent(d, c)).join(', ')} FROM ${quoteIdent(d, 'items')} ORDER BY 1`, [], 1000)
            // 소수는 DB마다 글자 모양이 달라서(12.50 / 12.5) 숫자로 비교
            expect(q.rows.map((r) => r.map((v, i) => (v === null ? null : i === 2 ? Number(v) : String(v))))).toEqual([['1', '가나다', 12.5, d === 'mssql' ? 'true' : '1'], ['2', 'b', null, d === 'mssql' ? 'false' : '0']])
          })
        }
        // SQLite 파일로
        const file = path.join(dir, 'x.db')
        fs.writeFileSync(file, '')
        await m.connect('lite', resolved(config('sqlite', { file })))
        const ll = m.get('lite')
        const res = await transferData({ mod: lp.mod, s: await m.editorSession(pg, 'src2', pdb, psch), db: pdb, schema: psch, o: O },
          { mod: ll.mod, s: await m.editorSession('lite', 'dst', 'main', ''), db: 'main', schema: '', o: O }, ['items'], { create: true, truncate: false, batch: 100, stopOnError: true }, () => false)
        expect(res.tables[0]).toMatchObject({ rows: 2, created: true, error: null })
        const q = await (await m.editorSession('lite', 'chk', 'main', '')).query('SELECT id, name, hex(data) FROM items ORDER BY id')
        expect(q.rows).toEqual([[1, '가나다', '00FF10'], [2, 'b', '']])
      })
    } finally {
      await m.disconnectAll()
      fs.rmSync(dir, { recursive: true, force: true })
    }
  })
})
