// 3-3단계 실제 서버(Docker): Oracle 전체 시나리오·설계·PL/SQL·덤프·사용자·세션, ClickHouse 탐색기·실행·취소·가져오기·설계·사용자, PostgreSQL → 새 DB 옮기기
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { describe, expect, it } from 'vitest'
import { Manager } from '../src/main/conn'
import * as ops from '../src/main/ops'
import { runSqlFile, runStatements, writeDump } from '../src/main/dump'
import { explain } from '../src/main/explain'
import { searchData, searchNames } from '../src/main/search'
import { transferData } from '../src/main/transfer'
